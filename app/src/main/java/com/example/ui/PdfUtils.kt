        p.color = NAVY; p.textSize = 12f; p.isFakeBoldText = true
        c.drawText("Summary", margin, yPos, p)
        yPos += 14f

        fun drawSummaryTable(
            title: String,
            headers: List<String>,
            rows: List<List<String>>,
